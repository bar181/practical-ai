"""build.py: makes base/game.html and base/examples/sample-pack.md from packs.json, stopwords.json and game.src.html.
Run: python3 projects/rare-find/_build/build.py
"""
import base64, json, os
here = os.path.dirname(os.path.abspath(__file__))
root = os.path.dirname(here)
data = json.load(open(os.path.join(here, "packs.json"), encoding="utf-8"))
src = open(os.path.join(here, "game.src.html"), encoding="utf-8").read()
assert "/*__PACKS__*/" in src
stop_path = os.path.join(here, "stopwords.json")
stop = json.load(open(stop_path)) if os.path.exists(stop_path) else []
assert "/*__STOP__*/" in src
html = (src.replace("/*__PACKS__*/", json.dumps(data, ensure_ascii=False, separators=(",", ":")))
           .replace("/*__STOP__*/", json.dumps(stop, separators=(",", ":")))
           .replace("__CREATOR_IMG__", "data:image/webp;base64," + base64.b64encode(open(os.path.join(here, "img", "creator.webp"), "rb").read()).decode()))
open(os.path.join(root, "base", "game.html"), "w", encoding="utf-8").write(html)

def names(lst):
    return "; ".join(e["a"] + (f" ({', '.join(e['aka'])})" if e.get("aka") else "") for e in lst)
out = ["<!-- Generated by _build/build.py from _build/packs.json. Edit packs.json, not this file. -->", "",
       "# The built-in packs", "",
       f"The {len(data['packs'])} prompts inside [`../game.html`](../game.html). **{data['estimated']}** "
       "Other names and spellings are in brackets; the game also forgives typos.", ""]
for p in data["packs"]:
    out += [f"## {p['prompt']}", "", f"*{p['cat']}*" + (f". {p['note']}" if p.get("note") else ""), "",
            "| Rank or tier | Points | Answers |", "| --- | --- | --- |",
            *[f"| #{i+1} | {round(25+(p.get('top',50)-25)*i/9)} | {names([e])} |" for i, e in enumerate(p['ranked'][:10])],
            f"| Gem | 100 | {names(p['gems'])} |",
            f"| Good find | 80 | {names(p['good'])} |",
            f"| Not accepted (examples) | 0 | {'; '.join(p['wrong'])} |", ""]
open(os.path.join(root, "base", "examples", "sample-pack.md"), "w", encoding="utf-8").write("\n".join(out))
print("built game.html", len(html), "bytes;", len(data["packs"]), "packs")
