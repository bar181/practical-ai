"""build_step_skills.py: split base/SKILL.md into one skill per step, in level-2-files/skills/.

  python3 _build/build_step_skills.py           write the seven step skills
  python3 _build/build_step_skills.py --check   exit 1 if they are out of date

base/SKILL.md is the single source. Each step skill holds that step's section, the parts of the
skill it needs (step 1 also gets "Set the depth and the voice"; step 7 also gets the brief and the
record layouts) and the Rules. Never edit the generated files: change base/SKILL.md and rebuild.
"""
import os, re, sys

here = os.path.dirname(os.path.abspath(__file__))
root = os.path.dirname(here)
src = open(os.path.join(root, "base", "SKILL.md"), encoding="utf-8").read()
body = src.split("---", 2)[2]
sections = {m.group(1).strip(): m.group(0) for m in re.finditer(r"(?ms)^## (.+?)$.*?(?=^## |\Z)", body)}
steps = {int(m.group(1)): (m.group(2).strip(), m.group(0).strip()) for m in
         re.finditer(r"(?ms)^### Step (\d)\. (.+?)$.*?(?=^### Step |\Z)", sections["The seven steps"])}
extra = {1: ["Set the depth and the voice"], 7: ["The decision brief (executive and team voice)",
                                                 "The decision record (technical voice)"]}
does = {1: "frames the decision as a question, with who decides, by when, what would change the answer and whether it can be undone",
        2: "lays out the options (always including do nothing), up to six criteria and the question broken into parts with no overlaps and no gaps",
        3: "puts a best guess on each part of the question and picks the two or three parts that decide the answer",
        4: "names, before any research, the evidence that would support each guess and the evidence that would prove it wrong",
        5: "gathers the evidence, quotes each source's exact words with its link and marks it checked or not, and builds the options table",
        6: "writes the answer in one sentence with three sourced reasons, the evidence against, a premortem with controls and a confidence level",
        7: "writes the one-page executive decision brief, or the technical decision record (ADR), from the earlier steps"}

out_dir = os.path.join(root, "level-2-files", "skills")
files = {}
for n, (name, text) in sorted(steps.items()):
    slug = f"decision-step-{n}-{name.lower().replace(' ', '-')}"
    parts = [f"""---
name: {slug}
description: Step {n} of 7 of decision support. It {does[n]}. Use when someone, or an agent running the process, asks for step {n} ("{name.lower()}") of a decision, {"or when a decision first comes up" if n == 1 else f"or after step {n - 1} is agreed"}.
license: Apache-2.0
metadata:
  author: Bradley Ross (https://www.linkedin.com/in/bradaross/)
  source: https://github.com/bar181/practical-ai/tree/main/projects/decision-support
---

<!-- Generated by projects/decision-support/_build/build_step_skills.py from base/SKILL.md. Do not edit: change base/SKILL.md and rebuild. -->

# Decision support, step {n} of 7: {name}

You do one step of a seven-step decision process. Use what the person, or the earlier steps, already
gave you. If something this step needs is missing, take the plainest reading and say so in one line.
Show this step's output under its heading, then stop and end with: "Correct anything above, or say
**go on**." The whole process, in one file, is the decision-support skill.
""".rstrip()]
    parts += [sections[s].strip() for s in extra.get(n, [])]
    parts += [text, sections["Rules"].strip()]
    files[os.path.join(out_dir, slug, "SKILL.md")] = "\n\n".join(parts).rstrip() + "\n"

if "--check" in sys.argv:
    stale = [p for p, t in files.items() if not os.path.exists(p) or open(p, encoding="utf-8").read() != t]
    print("step skills: " + ("up to date" if not stale else "out of date: " + ", ".join(os.path.relpath(p, root) for p in stale)))
    sys.exit(1 if stale else 0)
for path, text in files.items():
    os.makedirs(os.path.dirname(path), exist_ok=True)
    open(path, "w", encoding="utf-8").write(text)
print(f"wrote {len(files)} step skills to {os.path.relpath(out_dir, root)}/")
