"""build_site.py OUT_FOLDER: assemble the Practical AI web site that GitHub Pages publishes.

Copies the finished pages out of the repository and writes two small index pages. Nothing is
generated from scratch: every page on the site is a file already checked in.

  /                                   the Bradley Academy site, added on top by the workflow (projects/site-studio/)
  /artifact-studio/                   index for the two master pages and the worked examples
  /artifact-studio/showcase.html      master 1: photo, scroll and cinematic effects, layouts, social picture sizes, voices
  /artifact-studio/components.html    master 2: pages, decks, parts, design ideas, the picker, the skill
  /artifact-studio/base/examples/     the worked examples (same path as the repository, so their links work)
  /artifact-studio/try-it-keynote.html  the page the README's try-it prompt made
  /tone-studio/                       the seven tone landing pages
  /web-sections/                      the section library, the post previews and the café example (same paths as the repository's base/)
  /rare-find/                         the game, and how-it-was-made.html
  /reports/                           one explainer page per project

The home page and the tool pages are the React site in projects/site-studio/, which the workflow
builds and copies over this folder.
Run: python3 workshop/tools/build_site.py _site
"""
import html, os, shutil, sys

if len(sys.argv) != 2:
    sys.exit(__doc__)
ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
OUT = os.path.abspath(sys.argv[1])
STUDIO = os.path.join(ROOT, "projects", "artifact-studio")
REPO = "https://github.com/bar181/practical-ai"


def copy(src, dst):
    dst = os.path.join(OUT, dst)
    os.makedirs(os.path.dirname(dst), exist_ok=True)
    shutil.copyfile(os.path.join(ROOT, src), dst)


def title(path):
    text = open(os.path.join(ROOT, path), encoding="utf-8").read(20000)
    start = text.find("<title>") + 7
    return html.unescape(text[start:text.find("</title>", start)]).strip()


def page(name, heading, intro, sections):
    body = "".join(
        f"<h2>{html.escape(h)}</h2><ul>"
        + "".join(f'<li><a href="{href}">{html.escape(text)}</a>{": " + html.escape(note) if note else ""}</li>' for href, text, note in links)
        + "</ul>"
        for h, links in sections
    )
    out = os.path.join(OUT, name)
    os.makedirs(os.path.dirname(out), exist_ok=True)
    open(out, "w", encoding="utf-8").write(f"""<!DOCTYPE html>
<!-- Generated by workshop/tools/build_site.py. Change that script, not this file. -->
<html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width, initial-scale=1">
<title>{html.escape(heading)}</title>
<meta name="description" content="{html.escape(intro)}">
<style>
body{{font:400 17px/1.55 system-ui,-apple-system,"Segoe UI",sans-serif;color:#1b2228;background:#f6f8fb;margin:0}}
main{{max-width:620px;margin:0 auto;padding:44px 20px 60px}}
h1{{font-size:2rem;line-height:1.15;margin:0 0 10px}} h2{{font-size:1.15rem;margin:34px 0 8px}}
p{{margin:0 0 12px}} ul{{padding-left:1.2em;margin:0}} li{{margin:8px 0}}
a{{color:#1f4f8a;font-weight:600}} a:focus-visible{{outline:3px solid #d2b78c;outline-offset:2px}}
footer{{margin-top:44px;padding-top:16px;border-top:1px solid #d6dfea;font-size:.92rem;color:#4b596e}}
</style></head><body><main>
<h1>{html.escape(heading)}</h1><p>{html.escape(intro)}</p>{body}
<footer><a href="{REPO}">The tools on GitHub</a>. Made by Bradley Ross: <a href="https://www.linkedin.com/in/bradaross/">LinkedIn</a>.</footer>
</main></body></html>
""")


if os.path.exists(OUT):
    shutil.rmtree(OUT)

# Artifact Studio: the two master pages, the worked examples, and the page the try-it prompt made
copy("projects/artifact-studio/showcase.html", "artifact-studio/showcase.html")
copy("projects/artifact-studio/components.html", "artifact-studio/components.html")
copy("projects/artifact-studio/_build/examples/runs/2026-11-17-try-it-keynote-photo/report.html", "artifact-studio/try-it-keynote.html")
examples, lesson = [], []
for dirpath, _, files in os.walk(os.path.join(STUDIO, "base", "examples")):
    for f in sorted(files):
        rel = os.path.relpath(os.path.join(dirpath, f), STUDIO)
        copy(os.path.join("projects", "artifact-studio", rel), os.path.join("artifact-studio", rel))
        if f.endswith(".html"):
            stem = f[:-5]
            note = ("the " + stem[6:] + " voice" if stem.startswith("voice-") else
                    {"photo-effects": "photo effects", "report": "a one-page report",
                     "2-teacher": "the teacher version", "3-story": "the story version"}.get(stem, ""))
            (lesson if "before-after" in rel else examples).append((rel, title(os.path.join("projects", "artifact-studio", rel)), note))

# Web Sections: the section library, its photos, the post previews and the worked example, at the same relative paths
for dirpath, _, files in os.walk(os.path.join(ROOT, "projects", "web-sections", "base")):
    for f in files:
        if f.endswith((".html", ".jpg", ".svg")):
            rel = os.path.relpath(os.path.join(dirpath, f), os.path.join(ROOT, "projects", "web-sections"))
            copy(os.path.join("projects", "web-sections", rel), os.path.join("web-sections", rel))

# Tone Studio: the seven tone landing pages and their photos, at the same relative paths
for dirpath, _, files in os.walk(os.path.join(ROOT, "projects", "tone-studio", "base", "examples")):
    for f in files:
        if f.endswith((".html", ".jpg")):
            rel = os.path.relpath(os.path.join(dirpath, f), os.path.join(ROOT, "projects", "tone-studio"))
            copy(os.path.join("projects", "tone-studio", rel), os.path.join("tone-studio", rel))

# Rare Find: the game and how it was made
copy("projects/rare-find/base/game.html", "rare-find/index.html")
copy("docs/reports/rare-find.html", "rare-find/how-it-was-made.html")

# One explainer page per project
for f in sorted(os.listdir(os.path.join(ROOT, "docs", "reports"))):
    if f.endswith(".html"):
        copy(os.path.join("docs", "reports", f), os.path.join("reports", f))

page("artifact-studio/index.html", "Artifact Studio: every example",
     "Designer-quality pages, decks and posts, made in the chatbot you already use. Open any page below in your browser.",
     [("The two master pages", [
         ("showcase.html", "1. The showcase", "photo effects, scroll effects, layouts, post previews and seven voices"),
         ("components.html", "2. The components", "four pages, four decks, every part, the design ideas, the picker and the skill")]),
      ("Made by an AI from one prompt, unedited", [("try-it-keynote.html", "The page the try-it prompt made", "a scrolling keynote")] + sorted(examples)),
      ("One client lesson, made by the author from one source", lesson),
      ("Make your own", [(f"{REPO}/tree/main/projects/artifact-studio#try-it-now", "Copy the try-it prompt into your chatbot", "")])])

count = sum(len(fs) for _, _, fs in os.walk(OUT))
print(f"site: {count} files -> {OUT}")
